"""Expert dataset for Stage 1 V2: canonical A0 episodes on the clean curriculum environment -> (37-D observation, normalized A0 direction) pairs.

Restart-safe: each shard (500 scenarios) is generated by one worker under an exclusive lock, written atomically (npz, then its hashed sidecar manifest LAST), and a verified
shard is never regenerated. `dataset_manifest.json` (written last) records every shard hash, the dataset hash, the split definition and the geometry coverage.
"""

from __future__ import annotations

import hashlib
import io
import json
import multiprocessing as mp
import time
from pathlib import Path

import numpy as np

from experiments import journal_v2_a1_cur1v2 as V
from experiments import journal_v2_a1_eg_state as P  # atomic-write / lock primitives

DATA_DIR = V.RESULTS_ROOT / "dataset"
SHARD_EPISODES = V.EXPERT_EPISODES // V.EXPERT_SHARDS
SCHEMA = "a1_cur1v2_expert_shard/1"


def shard_path(i: int) -> Path:
    return DATA_DIR / f"expert_shard_{i:02d}.npz"


def sidecar_path(i: int) -> Path:
    return DATA_DIR / f"expert_shard_{i:02d}.json"


def shard_seeds(i: int) -> range:
    start = V.EXPERT_SEED_START + i * SHARD_EPISODES
    return range(start, start + SHARD_EPISODES)


def verify_shard(i: int, data_dir: Path | None = None, spec_sha: str | None = None) -> dict | None:
    base = Path(data_dir) if data_dir is not None else DATA_DIR
    try:
        side = json.loads((base / f"expert_shard_{i:02d}.json").read_text())
        if side.get("schema") != SCHEMA or side.get("shard") != i or side.get("env_config_sha256") != V.config_sha256():
            return None
        if P.sha256_file(base / f"expert_shard_{i:02d}.npz") != side["npz_sha256"]:
            return None
        return side
    except (OSError, ValueError, KeyError, TypeError):
        return None


def generate_expert_episodes(seeds) -> dict:
    """A0 (scripted, no override) on `seeds`; at every decision the masked observation and the A0 label of the same state are recorded."""
    env = V.Stage1V2Env(0, 0, 0, scripted_a0=True)
    obs_rows, act_rows, ep_idx, step_idx = [], [], [], []
    meta = {"seed": [], "steps": [], "initial_range": [], "bearing_deg": [], "altitude": [], "heading_offset_deg": [], "caught": [], "final_pairs_within_10m": []}
    for s in seeds:
        obs, _ = env.reset(options={"scenario": int(s)})
        e = env.soldier_env
        rel = np.asarray(e._enemy_pos, dtype=np.float64)
        done, t, near = False, 0, 0
        while not done:
            obs_rows.append(obs.astype(np.float32))
            act_rows.append(env.expert_action())
            ep_idx.append(int(s))
            step_idx.append(t)
            near += int(float(np.linalg.norm(np.asarray(e._enemy_pos, dtype=np.float64) - np.asarray(e._soldier_pos, dtype=np.float64))) <= 10.0)
            obs, _r, te, tr, info = env.step(np.zeros(3, dtype=np.float32))
            done, t = te or tr, t + 1
        ep = info["a1_episode"]
        meta["seed"].append(int(s)); meta["steps"].append(int(ep["steps"])); meta["initial_range"].append(float(ep["initial_range_m"]))
        meta["bearing_deg"].append(float(np.degrees(np.arctan2(rel[1], rel[0])))); meta["altitude"].append(float(ep["initial_altitude_m"]))
        meta["heading_offset_deg"].append(float(ep["initial_heading_offset_deg"])); meta["caught"].append(bool(ep["outcome"] == "soldier_caught")); meta["final_pairs_within_10m"].append(int(near))
    return {"obs": np.asarray(obs_rows, dtype=np.float32), "act": np.asarray(act_rows, dtype=np.float32), "ep_seed": np.asarray(ep_idx, dtype=np.int64),
            "step": np.asarray(step_idx, dtype=np.int16), **{f"meta_{k}": np.asarray(v) for k, v in meta.items()}}


def npz_bytes(arrays: dict) -> bytes:
    buffer = io.BytesIO()
    np.savez(buffer, **arrays)
    return buffer.getvalue()


def write_shard(i: int, data_dir: Path | None = None, seeds=None) -> dict:
    base = Path(data_dir) if data_dir is not None else DATA_DIR
    if verify_shard(i, base) is not None:
        return {"shard": i, "skipped": True}
    lock = P.CellLock(base / f"expert_shard_{i:02d}")
    if not lock.acquire():
        return {"shard": i, "skipped": True, "reason": "another worker owns this shard"}
    try:
        started = time.time()
        seeds = list(seeds if seeds is not None else shard_seeds(i))
        arrays = generate_expert_episodes(seeds)
        payload = npz_bytes(arrays)
        P.atomic_write_bytes(base / f"expert_shard_{i:02d}.npz", payload)
        side = {"schema": SCHEMA, "shard": i, "episodes": len(seeds), "seed_range": [seeds[0], seeds[-1]], "pairs": int(arrays["obs"].shape[0]), "npz_sha256": hashlib.sha256(payload).hexdigest(),
                "env_config_sha256": V.config_sha256(), "created_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
        P.atomic_write_json(base / f"expert_shard_{i:02d}.json", side)       # sidecar LAST = commit marker
        return {"shard": i, "pairs": side["pairs"], "seconds": round(time.time() - started, 1)}
    finally:
        lock.release()


def _worker(i: int) -> dict:
    return write_shard(i)


def generate(workers: int = 10) -> dict:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    for stale in DATA_DIR.glob(".*.tmp*"):
        stale.unlink(missing_ok=True)
    pending = [i for i in range(V.EXPERT_SHARDS) if verify_shard(i) is None]
    print(f"{V.EXPERT_SHARDS - len(pending)} shards already verified, {len(pending)} to generate", flush=True)
    if pending:
        with mp.get_context("spawn").Pool(min(workers, len(pending))) as pool:
            for r in pool.imap_unordered(_worker, pending):
                print(r, flush=True)
    return finalize()


# ----------------------------------------------------------------------------- loading, split, coverage, manifest
def load_all(data_dir: Path | None = None) -> dict:
    base = Path(data_dir) if data_dir is not None else DATA_DIR
    parts = []
    for i in range(V.EXPERT_SHARDS):
        if verify_shard(i, base) is None:
            raise RuntimeError(f"shard {i} is missing or fails verification")
        with np.load(base / f"expert_shard_{i:02d}.npz") as z:
            parts.append({k: z[k] for k in z.files})
    return {k: np.concatenate([p[k] for p in parts]) for k in parts[0]}


def split(data: dict) -> dict:
    """Episode-level 80/20 split. Returns {'train': (obs, act), 'val': (obs, act), 'train_episodes': set, 'val_episodes': set}."""
    train_flags = V.split_table(V.EXPERT_SEED_START, V.EXPERT_EPISODES)
    index = data["ep_seed"] - V.EXPERT_SEED_START
    is_train = train_flags[index]
    seeds = np.unique(data["ep_seed"])
    tr = {int(s) for s in seeds if train_flags[int(s) - V.EXPERT_SEED_START]}
    va = {int(s) for s in seeds} - tr
    return {"train": (data["obs"][is_train], data["act"][is_train]), "val": (data["obs"][~is_train], data["act"][~is_train]), "train_episodes": tr, "val_episodes": va}


def coverage(data: dict) -> dict:
    steps, rng, bearing, alt, off = data["meta_steps"], data["meta_initial_range"], data["meta_bearing_deg"], data["meta_altitude"], data["meta_heading_offset_deg"]
    quadrants = [int(((bearing >= lo) & (bearing < hi)).sum()) for lo, hi in ((-180, -90), (-90, 0), (0, 90), (90, 180.001))]
    asset_rel = np.linalg.norm(data["obs"][:, 3:6] - data["obs"][:, 0:3], axis=1)   # normalized attacker-asset offset (diagnostic only)
    return {
        "episodes": int(len(steps)), "pairs": int(data["obs"].shape[0]), "pairs_per_episode_mean": float(steps.mean()), "pairs_per_episode_min_max": [int(steps.min()), int(steps.max())],
        "caught_fraction": float(np.mean(data["meta_caught"])), "bearing_quadrant_episode_counts": quadrants, "initial_range_m": [float(rng.min()), float(np.median(rng)), float(rng.max())],
        "initial_altitude_m": [float(alt.min()), float(np.median(alt)), float(alt.max())], "heading_offset_deg": [float(off.min()), float(np.median(off)), float(off.max())],
        "heading_offset_quartile_counts": [int(((off >= a) & (off < b)).sum()) for a, b in ((0, 22.5), (22.5, 45), (45, 67.5), (67.5, 90.001))],
        "late_approach_pairs_within_10m": int(data["meta_final_pairs_within_10m"].sum()), "late_approach_fraction": float(data["meta_final_pairs_within_10m"].sum() / data["obs"].shape[0]),
        "step_index_histogram": [int((data["step"] == k).sum()) for k in range(int(data["step"].max()) + 1)], "normalized_offset_min_max": [float(asset_rel.min()), float(asset_rel.max())],
        "action_norm_min_max": [float(np.linalg.norm(data["act"], axis=1).min()), float(np.linalg.norm(data["act"], axis=1).max())],
        "vertical_component_of_label": [float(data["act"][:, 2].min()), float(np.median(data["act"][:, 2])), float(data["act"][:, 2].max())],
    }


def dataset_sha256(data_dir: Path | None = None) -> str:
    base = Path(data_dir) if data_dir is not None else DATA_DIR
    digest = hashlib.sha256()
    for i in range(V.EXPERT_SHARDS):
        side = verify_shard(i, base)
        if side is None:
            raise RuntimeError(f"shard {i} missing/unverified")
        digest.update(side["npz_sha256"].encode())
    return digest.hexdigest()


def finalize(data_dir: Path | None = None) -> dict:
    base = Path(data_dir) if data_dir is not None else DATA_DIR
    data = load_all(base)
    sp = split(data)
    leakage = sp["train_episodes"] & sp["val_episodes"]
    manifest = {"schema": "a1_cur1v2_expert_dataset/1", "shards": [verify_shard(i, base) for i in range(V.EXPERT_SHARDS)], "dataset_sha256": dataset_sha256(base),
                "pairs": int(data["obs"].shape[0]), "train_pairs": int(sp["train"][0].shape[0]), "val_pairs": int(sp["val"][0].shape[0]),
                "train_episodes": len(sp["train_episodes"]), "val_episodes": len(sp["val_episodes"]), "episode_leakage": len(leakage), "coverage": coverage(data),
                "observation_version": V.OBSERVATION_VERSION, "env_config_sha256": V.config_sha256(), "expert_scenarios": [V.EXPERT_SEED_START, V.EXPERT_SEED_START + V.EXPERT_EPISODES - 1]}
    if leakage:
        raise RuntimeError("episode leakage between train and validation")
    P.atomic_write_json(base / "dataset_manifest.json", manifest)
    return manifest


